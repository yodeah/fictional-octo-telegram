import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

// The Fight Sim is the Underworld Duel page at the repository root (index.html + hades/). It stays
// plain JS with no build step; this plugin serves it at /fight.html in dev, copies it into the build
// and writes a service worker that precaches every file so both modes work offline.
const repo = resolve(import.meta.dirname, '..');
const hadesDir = join(repo, 'hades');
const publicDir = resolve(import.meta.dirname, 'public');

function fightPage(): string {
  const html = readFileSync(join(repo, 'index.html'), 'utf8');
  const back = '<a class="menu-back" href="./" style="position:fixed;bottom:12px;right:12px;box-shadow:0 4px 14px #000a;z-index:9;margin:0;padding:6px 12px;' +
    'background:#0d2a31;border:1px solid #8b6c33;border-radius:4px;color:#ffd98a;text-decoration:none">&larr; Menu</a>';
  return html
    .replace('<title>Underworld Duel</title>', '<title>Fight Sim · Ash &amp; Obol</title>\n  <link rel="manifest" href="./manifest.webmanifest">')
    .replace('<body>', '<body>\n  ' + back);
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

function fightSimAndOffline(): Plugin {
  return {
    name: 'fight-sim-and-offline',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const url = (req.url || '').split('?')[0];
        if (url.endsWith('/fight.html')) {
          res.setHeader('Content-Type', 'text/html');
          res.end(fightPage());
          return;
        }
        const at = url.indexOf('/hades/');
        if (at >= 0) {
          const file = join(hadesDir, url.slice(at + 7));
          if (file.startsWith(hadesDir)) {
            try {
              const body = readFileSync(file);
              res.setHeader('Content-Type', file.endsWith('.css') ? 'text/css' : 'text/javascript');
              res.end(body);
              return;
            } catch { /* fall through to Vite */ }
          }
        }
        next();
      });
    },
    generateBundle: {
      order: 'post',
      handler(_options, bundle) {
        // Files emitted here don't show up in `bundle` yet, so they are listed by hand.
        const extra: [string, string | Uint8Array][] = [['fight.html', fightPage()],
          ...readdirSync(hadesDir).map(file => [`hades/${file}`, readFileSync(join(hadesDir, file))] as [string, Uint8Array])];
        const hash = createHash('sha256');
        const files = ['./'];
        for (const [fileName, source] of extra) {
          this.emitFile({ type: 'asset', fileName, source });
          files.push('./' + fileName);
          hash.update(fileName);
          hash.update(source);
        }
        for (const [name, item] of Object.entries(bundle)) {
          files.push('./' + name);
          hash.update(name);
          hash.update(item.type === 'chunk' ? item.code : item.source);
        }
        for (const path of listFiles(publicDir)) {
          const name = relative(publicDir, path).split('\\').join('/');
          files.push('./' + name);
          hash.update(name);
          hash.update(readFileSync(path));
        }
        const version = hash.digest('hex').slice(0, 12);
        this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files.sort()) });
      }
    }
  };
}

function serviceWorker(version: string, files: string[]): string {
  return `// Generated by vite.config.ts. Precaches the whole build so the app runs offline.
const CACHE = 'ash-obol-${version}';
const FILES = ${JSON.stringify(files, null, 1)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith('ash-obol-') && key !== CACHE).map(key => caches.delete(key))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== location.origin) return;
  event.respondWith(caches.open(CACHE).then(cache => cache.match(request, { ignoreSearch: true }).then(hit => hit
    || fetch(request).catch(() => request.mode === 'navigate' ? cache.match('./index.html') : Response.error()))));
});
`;
}

export default defineConfig({
  base: './',
  plugins: [react(), fightSimAndOffline()],
  server: { port: 8163, strictPort: true },
  preview: { port: 8164, strictPort: true },
  build: { target: 'es2022' }
});
